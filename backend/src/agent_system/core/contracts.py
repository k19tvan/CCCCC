"""Shared Pydantic data contracts for the issue agent, its tools and the app.

This module must not import any other internal module.
"""

from __future__ import annotations

from typing import Any, Literal

from pydantic import BaseModel, Field

Route = Literal["answer", "fix", "implement", "ask_user", "reject"]
IssueType = Literal["bug", "feature", "refactor", "docs", "question", "invalid"]
Priority = Literal["P0", "P1", "P2", "P3"]


class IssueRequest(BaseModel):
    """Input sent by the app or user to the agent."""

    title: str = Field(..., description="Short issue title")
    description: str = Field(..., description="Detailed issue description")
    clarified_text: str | None = Field(
        default=None,
        description="Clarification text after the user answers the agent's questions",
    )
    repo_path: str = Field(default=".", description="Path to the target Python repo")
    request_id: str | None = Field(
        default=None, description="Request ID; generated by the orchestrator if None"
    )


class IssueTicket(BaseModel):
    """Structured issue ticket produced by the agent."""

    type: IssueType = Field(..., description="Issue type")
    priority: Priority = Field(..., description="Priority level P0-P3")
    priority_reason: str = Field(..., description="Short reason for the priority")
    affected_files: list[str] = Field(
        default_factory=list,
        description="Paths of affected files (at most 5, must exist in the repo)",
    )
    reproduction_steps: list[str] = Field(
        default_factory=list,
        description="Steps to reproduce (for bugs); empty if they cannot be inferred",
    )
    acceptance_criteria: list[str] = Field(
        default_factory=list,
        description="At least one testable criterion",
    )
    missing_info: list[str] = Field(
        default_factory=list,
        description="Information still missing to handle the issue; empty list = nothing missing",
    )
    route: Route = Field(
        default="ask_user",
        description="Next processing route",
    )
    clarification_questions: list[str] = Field(
        default_factory=list,
        description="Clarification questions when route=ask_user",
    )
    summary: str = Field(default="", description="Short summary of the issue")


class IssueResult(BaseModel):
    """Result returned by the agent to the app."""

    status: Literal["completed", "needs_user", "failed"] = Field(
        ..., description="Processing status"
    )
    ticket: IssueTicket | None = Field(default=None, description="Issue ticket, if one could be created")
    message: str = Field(default="", description="Short message for the user")
    warnings: list[str] = Field(
        default_factory=list,
        description="Warnings (e.g. file does not exist, path traversal blocked)",
    )
    run_id: str = Field(default="", description="Run ID used for tracing")
    trace: list[dict[str, Any]] = Field(
        default_factory=list, description="Log of execution steps"
    )


class ToolInput(BaseModel):
    """Base class for all tool inputs."""

    pass


class ToolOutput(BaseModel):
    """Base class for all tool outputs."""

    success: bool = Field(..., description="True if the tool executed successfully")
    error: str | None = Field(default=None, description="Error message if success=False")


class ListFilesInput(ToolInput):
    """Input for the list_files tool."""

    repo_path: str = Field(..., description="Root path of the repo")
    subdirectory: str = Field(
        default="",
        description="Subdirectory to list (relative to repo_path); empty = root",
    )
    extensions: list[str] = Field(
        default_factory=list,
        description="Filter by extension, e.g. ['.py', '.md']; empty = all",
    )
    max_results: int = Field(default=100, ge=1, le=500, description="Maximum number of results")


class ListFilesOutput(ToolOutput):
    """Output of the list_files tool."""

    files: list[str] = Field(
        default_factory=list,
        description="List of paths relative to repo_path",
    )
    total_found: int = Field(default=0, description="Total files found before truncation")
    truncated: bool = Field(default=False, description="True if the results were truncated")


class ReadFileInput(ToolInput):
    """Input for the read_file tool."""

    repo_path: str = Field(..., description="Root path of the repo")
    file_path: str = Field(
        ...,
        description="File path relative to repo_path",
    )
    start_line: int | None = Field(default=None, ge=1, description="Start line (1-indexed)")
    end_line: int | None = Field(default=None, ge=1, description="End line (1-indexed, inclusive)")
    max_chars: int = Field(
        default=10_000,
        ge=1,
        le=100_000,
        description="Maximum number of characters returned",
    )


class ReadFileOutput(ToolOutput):
    """Output of the read_file tool."""

    content: str = Field(default="", description="File content (or the requested range)")
    file_path: str = Field(default="", description="Relative path that was read")
    total_lines: int = Field(default=0, description="Total number of lines in the file")
    start_line: int = Field(default=1, description="Line actually read from")
    end_line: int = Field(default=0, description="Line actually read to")
    truncated: bool = Field(default=False, description="True if the content was truncated")
    encoding: str = Field(default="utf-8", description="Encoding used to read the file")


class SearchCodeInput(ToolInput):
    """Input for the search_code tool."""

    repo_path: str = Field(..., description="Root path of the repo")
    query: str = Field(..., description="Search string or regex pattern")
    is_regex: bool = Field(default=False, description="True if query is a regex")
    file_extensions: list[str] = Field(
        default_factory=list,
        description="Filter by extension, e.g. ['.py']; empty = all",
    )
    case_sensitive: bool = Field(default=False, description="Case-sensitive match")
    max_results: int = Field(default=50, ge=1, le=200, description="Maximum number of results")
    context_lines: int = Field(
        default=2, ge=0, le=10, description="Number of context lines around each match"
    )


class SearchMatch(BaseModel):
    """A single match from search_code."""

    file_path: str = Field(..., description="Path relative to repo_path")
    line_number: int = Field(..., description="Line number (1-indexed)")
    line_content: str = Field(..., description="Content of the matching line")
    context_before: list[str] = Field(
        default_factory=list, description="Context lines before the match"
    )
    context_after: list[str] = Field(
        default_factory=list, description="Context lines after the match"
    )


class SearchCodeOutput(ToolOutput):
    """Output of the search_code tool."""

    matches: list[SearchMatch] = Field(
        default_factory=list, description="List of matches found"
    )
    total_matches: int = Field(default=0, description="Total matches before truncation")
    truncated: bool = Field(default=False, description="True if the results were truncated")
    query: str = Field(default="", description="Query that was searched")


class ContextSource(BaseModel):
    """A piece of collected context."""

    tool_name: str = Field(..., description="Name of the tool used")
    file_path: str | None = Field(default=None, description="Related file, if any")
    line_number: int | None = Field(default=None, description="Line number, if any")
    content: str = Field(..., description="Content/excerpt from this source")
    relevance_note: str = Field(default="", description="Note on relevance")


class GatherContextInput(BaseModel):
    """Input for the gather_context skill."""

    title: str = Field(..., description="Issue title")
    description: str = Field(..., description="Issue description")
    repo_path: str = Field(..., description="Root path of the repo")
    clarified_text: str | None = Field(default=None, description="Clarification from the user, if any")


class GatherContextOutput(BaseModel):
    """Output of the gather_context skill."""

    sources: list[ContextSource] = Field(
        default_factory=list,
        description="Collected context sources",
    )
    files_found: list[str] = Field(
        default_factory=list,
        description="Relevant files found in the repo",
    )
    keywords_used: list[str] = Field(
        default_factory=list,
        description="Keywords used for searching",
    )
    tools_called: list[str] = Field(
        default_factory=list,
        description="Tools that were called",
    )
    summary: str = Field(
        default="",
        description="Summary of the collected context for the LLM",
    )


class ValidationResult(BaseModel):
    """Result from the validation module."""

    is_valid: bool = Field(..., description="True if the ticket is fully valid")
    errors: list[str] = Field(
        default_factory=list,
        description="Schema errors to fix (when is_valid=False)",
    )
    warnings: list[str] = Field(
        default_factory=list,
        description="Non-blocking warnings (e.g. file does not exist)",
    )
    valid_files: list[str] = Field(
        default_factory=list,
        description="Files confirmed to exist in the repo",
    )
    invalid_files: list[str] = Field(
        default_factory=list,
        description="Files that do not exist or are outside the repo",
    )
